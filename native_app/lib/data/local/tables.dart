import 'package:drift/drift.dart';

/// Local SQLite table for books (source of truth for clerk/collector UI).
class Books extends Table {
  TextColumn get id => text()(); // UUID generated by client
  TextColumn get isbn => text().nullable()();
  TextColumn get title => text().nullable()();
  TextColumn get author => text().nullable()();
  TextColumn get author2 => text().nullable()();
  TextColumn get author3 => text().nullable()();
  TextColumn get author4 => text().nullable()();
  TextColumn get author5 => text().nullable()();
  TextColumn get publisher => text().nullable()();
  TextColumn get year => text().nullable()();
  IntColumn get quantity => integer().withDefault(const Constant(1))();
  TextColumn get condition => text().nullable()(); // Good | Fair | Poor
  TextColumn get category => text().nullable()();
  TextColumn get shelfLocation => text().nullable()();
  TextColumn get notes => text().nullable()();
  TextColumn get schoolId => text()();
  TextColumn get clerkId => text()();
  BoolColumn get flaggedAsDuplicate =>
      boolean().withDefault(const Constant(false))();
  TextColumn get syncState =>
      text().withDefault(const Constant('pending'))(); // pending | synced | failed
  DateTimeColumn get updatedAt => dateTime().withDefault(currentDateAndTime)();

  @override
  Set<Column> get primaryKey => {id};
}

/// Outbox table for offline-first sync engine.
class Outbox extends Table {
  IntColumn get seq => integer().autoIncrement()();
  TextColumn get entity => text()(); // 'book'
  TextColumn get entityId => text()();
  TextColumn get op => text()(); // 'upsert' | 'delete'
  TextColumn get payload => text()(); // JSON string
  IntColumn get attempts => integer().withDefault(const Constant(0))();
  TextColumn get lastError => text().nullable()();
  DateTimeColumn get createdAt => dateTime().withDefault(currentDateAndTime)();
}

/// Metadata cache for fast local ISBN lookup when offline.
class MetadataCache extends Table {
  TextColumn get isbn => text()();
  TextColumn get title => text().nullable()();
  TextColumn get author => text().nullable()();
  TextColumn get author2 => text().nullable()();
  TextColumn get author3 => text().nullable()();
  TextColumn get author4 => text().nullable()();
  TextColumn get author5 => text().nullable()();
  TextColumn get publisher => text().nullable()();
  TextColumn get year => text().nullable()();
  TextColumn get category => text().nullable()();
  DateTimeColumn get updatedAt => dateTime().withDefault(currentDateAndTime)();

  @override
  Set<Column> get primaryKey => {isbn};
}

/// Locally cached schools for offline clerk selection.
class SchoolsTable extends Table {
  TextColumn get id => text()();
  TextColumn get name => text()();
  TextColumn get district => text().nullable()();
  TextColumn get region => text().nullable()();
  BoolColumn get active => boolean().withDefault(const Constant(true))();

  @override
  Set<Column> get primaryKey => {id};
}
